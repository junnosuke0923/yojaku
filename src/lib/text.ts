/**
 * 画面に出る**説明文と注意書き**を、ここに集めてある（依頼者の指示・2026-09-02）。
 *
 * ## なぜ集めたか
 *
 * 依頼者自身が文言を打ち替えられるようにするため。
 * ばらばらの file の中に直接書いてあると、打ち替えの口を作りようがない。
 *
 *   「各箇所に書かれている文言を僕の方でも打ち込みで修正し、
 *     最終的にはそれを本体に反映できるような、開発ページが欲しいです」
 *
 * ## 集めたのは説明と注意書きだけ
 *
 * ボタンの文字、段階の名前（撮る／測る／縫い代／生地／並べる）、
 * 選択肢の名前、エラーの文は**ここには入れていない**（依頼者の選択・2026-09-02）。
 * それらは短く、押したときに何が起きるかと結びついているので、
 * 打ち替えると動きのほうと食いちがう恐れがある。
 * 直したくなるのはたいてい説明文なので、そこに絞ってある。
 *
 * ## 言い回しの理由も、ここへ運んである
 *
 * もとは文言のすぐ横に「なぜこう書いたか」を書いていた。集めるにあたって、
 * その理由も `why` として一緒に運んである。
 * 理由の見えないところで文言だけ直せてしまうと、
 * 前に一度失敗した書き方へ戻ってしまう。
 *
 * ## 書き方の決まり
 *
 *   `*ここ*`   … 太字になる
 *   `[ここ]`   … 赤くなる（「わ」や縫い代と同じ色）
 *   `{n}`      … 数字が入る。**消さないこと**（消すと数字が出なくなる）
 *   改行       … そのまま改行になる
 */


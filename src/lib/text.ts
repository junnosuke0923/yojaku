export type TextId = keyof typeof TEXTS

/**
 * 1つ取り出す。`why` を書いていない文言があるので、
 * ここで `Entry` に均しておかないと、取り出すたびに有無を見る羽目になる
 */
export const entryOf = (id: TextId): Entry => TEXTS[id]

/** 画面ごとに分けた id の並び。一覧はこの順に出す */
export const idsByScreen = (): Array<[Screen, TextId[]]> =>
  SCREENS.map((s): [Screen, TextId[]] => [
    s,
    (Object.keys(TEXTS) as TextId[]).filter((id) => TEXTS[id].screen === s),
  ]).filter(([, ids]) => ids.length > 0)
